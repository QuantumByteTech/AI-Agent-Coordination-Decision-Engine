from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session

from app.database.database import get_db
from app.database.models import AgentActivityLog
from app.auth.dependencies import require_hr

router = APIRouter(
    prefix="/api/agents",
    tags=["Agent Monitoring"]
)


@router.get("/activity")
def get_agent_activity(
    db: Session = Depends(get_db),
    current_user=Depends(require_hr)
):
    """
    Return recent activity generated by AI agents.
    """

    activities = (
        db.query(AgentActivityLog)
        .order_by(
            AgentActivityLog.timestamp.desc()
        )
        .limit(200)
        .all()
    )

    return {
        "success": True,
        "count": len(activities),
        "activities": [
            {
                "id": activity.id,
                "workflow_id": activity.workflow_id,
                "agent_name": activity.agent_name,
                "action": activity.action,
                "status": activity.status,
                "message": activity.message,
                "timestamp": (
                    str(activity.timestamp)
                    if activity.timestamp
                    else None
                )
            }
            for activity in activities
        ]
    }


@router.get("/activity/{workflow_id}")
def get_workflow_agent_activity(
    workflow_id: str,
    db: Session = Depends(get_db),
    current_user=Depends(require_hr)
):
    """
    Return all agent activity for one workflow.
    """

    activities = (
        db.query(AgentActivityLog)
        .filter(
            AgentActivityLog.workflow_id == workflow_id
        )
        .order_by(
            AgentActivityLog.timestamp.asc()
        )
        .all()
    )

    return {
        "success": True,
        "workflow_id": workflow_id,
        "count": len(activities),
        "activities": [
            {
                "id": activity.id,
                "agent_name": activity.agent_name,
                "action": activity.action,
                "status": activity.status,
                "message": activity.message,
                "timestamp": (
                    str(activity.timestamp)
                    if activity.timestamp
                    else None
                )
            }
            for activity in activities
        ]
    }